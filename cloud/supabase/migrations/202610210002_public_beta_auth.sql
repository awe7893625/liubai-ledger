-- Liubai Ledger public beta auth without external SMTP.
-- Supabase still owns password hashing and sessions. Public usernames map to
-- internal non-routable auth emails; recovery uses a high-entropy one-time code.

alter table public.ledger_profiles
  add column if not exists username_norm text,
  add column if not exists username_display text;

create unique index if not exists ledger_profiles_username_norm_uidx
  on public.ledger_profiles(username_norm)
  where username_norm is not null;

create table if not exists public.ledger_recovery_codes (
  user_id uuid primary key references auth.users(id) on delete cascade,
  code_hash text not null,
  created_at timestamptz not null default now(),
  rotated_at timestamptz not null default now()
);

create table if not exists public.ledger_auth_attempts (
  id bigint generated by default as identity primary key,
  route text not null,
  bucket_hash text not null,
  created_at timestamptz not null default now()
);

create index if not exists ledger_auth_attempts_bucket_idx
  on public.ledger_auth_attempts(route, bucket_hash, created_at desc);

alter table public.ledger_recovery_codes enable row level security;
alter table public.ledger_auth_attempts enable row level security;

revoke all on public.ledger_recovery_codes from anon, authenticated;
revoke all on public.ledger_auth_attempts from anon, authenticated;

-- No browser policies: these tables are server-only and service-role mediated.
