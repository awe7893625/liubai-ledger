"""Build the Cloud v2 Shortcut from auditable plist primitives.

One Shortcut serves two inputs:
- Text "pair:<opaque-ticket>" from shortcuts://x-callback-url -> pair and store device token.
- Dictionary from the Wallet Transaction automation -> ingest amount/merchant/card/name.

No user token, card, account, or private URL is embedded in source control.
"""
from __future__ import annotations

import json
import os
import plistlib
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "shortcuts" / "src" / "Liubai-Cloud.plist"
UNSIGNED = ROOT / "shortcuts" / "source" / "Liubai-Cloud.unsigned.shortcut"
API_BASE = os.environ.get("LEDGER_CLOUD_API_BASE", "https://PROJECT.vercel.app").rstrip("/")
PAIR_URL = API_BASE + "/api/v2/pair/exchange"
INGEST_URL = API_BASE + "/api/v2/wallet/ingest"
NAMESPACE = uuid.UUID("447d32f5-a096-4be8-aada-4bb8b6aa88d2")


def ident(name: str) -> str:
    return str(uuid.uuid5(NAMESPACE, name)).upper()


def action(kind: str, name: str, **params):
    return {
        "WFWorkflowActionIdentifier": "is.workflow.actions." + kind,
        "WFWorkflowActionParameters": {"UUID": ident(name), **params},
    }
def output(name: str, output_name: str | None = None):
    return {
        "Value": {
            "Type": "ActionOutput",
            "OutputUUID": ident(name),
            "OutputName": output_name or name,
        },
        "WFSerializationType": "WFTextTokenAttachment",
    }


def extension_input():
    return {
        "Value": {"Type": "ExtensionInput"},
        "WFSerializationType": "WFTextTokenAttachment",
    }


def text(value: str):
    return {
        "Value": {"string": value},
        "WFSerializationType": "WFTextTokenString",
    }


def token(name: str, output_name: str | None = None):
    return {
        "Value": {
            "string": "\ufffc",
            "attachmentsByRange": {
                "{0, 1}": output(name, output_name)["Value"],
            },
        },
        "WFSerializationType": "WFTextTokenString",
    }
def dictionary(items):
    return {
        "Value": {
            "WFDictionaryFieldValueItems": [
                {"WFItemType": 0, "WFKey": text(key), "WFValue": value}
                for key, value in items
            ]
        },
        "WFSerializationType": "WFDictionaryFieldValue",
    }


def wrapped_output(name: str, output_name: str | None = None):
    return {"Type": "Variable", "Variable": output(name, output_name)}


def conditional(
    name: str,
    group: str,
    mode: int,
    *,
    equals: str | None = None,
    input_name: str | None = None,
):
    params = {"GroupingIdentifier": group, "WFControlFlowMode": mode}
    if mode == 0:
        params["WFCondition"] = 4
        params["WFInput"] = wrapped_output(input_name or "input-type", "Type")
        params["WFConditionalActionString"] = equals or ""
    return action("conditional", name, **params)


def build():
    branch = ident("mode-group")
    incoming = extension_input()
    actions = [
        action(
            "comment",
            "help",
            WFCommentActionText=(
                "留白自動記帳 · Cloud v2\n"
                "第一次由留白網站的「連接這支 iPhone」按鈕啟動；之後由 Wallet 交易自動化呼叫。\n"
                "裝置憑證只存於你的 Shortcuts iCloud Drive，不需要手動貼 API Token。"
            ),
        ),
        action(
            "comment",
            "playground-prompt",
            WFCommentActionText=(
                "Shortcuts generated by Shortcuts Playground.\n"
                "請在加入前檢查網路請求、檔案儲存與 Wallet 輸入是否符合預期。"
            ),
        ),
        action("getitemtype", "input-type", WFInput=incoming),
        action(
            "comment",
            "mode-help",
            WFCommentActionText=(
                "依輸入種類切換模式：\n"
                "- Text：網站一次性配對票券，只用來換裝置憑證。\n"
                "- Dictionary：Wallet 自動化傳入 amount、merchant、card。"
            ),
        ),
        conditional("if-pairing", branch, 0, equals="Text", input_name="input-type"),
    ]
    actions += [
        action(
            "comment",
            "pair-help",
            WFCommentActionText="配對模式：向留白 Cloud 交換裝置憑證，寫入 Shortcuts/iCloud Drive 後結束。",
        ),
        action("url", "pair-url", WFURLActionURL=PAIR_URL),
        action(
            "downloadurl",
            "pair-response",
            WFURL=output("pair-url"),
            WFHTTPMethod="POST",
            WFHTTPBodyType="JSON",
            WFHTTPHeaders=dictionary([("Content-Type", text("application/json"))]),
            WFJSONValues=dictionary([
                ("pair_ticket", incoming),
                ("device_name", text("iPhone")),
            ]),
        ),
        action(
            "getvalueforkey",
            "device-token",
            WFDictionaryKey="device_token",
            WFInput=output("pair-response"),
            WFGetDictionaryValueType="Value",
        ),
        action(
            "setitemname",
            "token-file",
            WFInput=output("device-token"),
            WFName="device-token.txt",
            WFDontIncludeFileExtension=False,
        ),
        action(
            "documentpicker.save",
            "save-token",
            WFInput=output("token-file", "Renamed Item"),
            WFAskWhereToSave=False,
            WFFileDestinationPath="Shortcuts/LiubaiLedger/",
            WFSaveFileOverwrite=True,
        ),
        action(
            "notification",
            "paired-notice",
            WFNotificationActionTitle="留白 Ledger",
            WFNotificationActionBody="這支 iPhone 已連接，接著到「自動化 → 交易」選卡片。",
            WFNotificationActionSound=False,
        ),
        action("exit", "pair-exit"),
        conditional("else-wallet", branch, 1),
        action(
            "documentpicker.open",
            "token-file-read",
            WFFileErrorIfNotFound=False,
            WFGetFolderContents=False,
            WFGetFilePath="Shortcuts/LiubaiLedger/device-token.txt",
            WFShowFilePicker=False,
        ),
        action("detect.text", "token-text", WFInput=output("token-file-read")),
        action(
            "comment",
            "wallet-help",
            WFCommentActionText=(
                "Wallet 模式：讀取已配對的裝置憑證，取得本次交易欄位，"
                "用同一個執行時間建立 request id 後送到留白 Cloud。"
            ),
        ),
        action("date", "request-date", WFDateActionMode="Current Date"),
        action(
            "format.date",
            "request-id",
            WFDate=token("request-date"),
            WFDateFormatStyle="ISO 8601",
        ),
    ]
    for field in ("amount", "merchant", "card"):
        actions.append(
            action(
                "getvalueforkey",
                "wallet-" + field,
                WFDictionaryKey=field,
                WFInput=incoming,
                WFGetDictionaryValueType="Value",
            )
        )
    actions += [
        action("url", "ingest-url", WFURLActionURL=INGEST_URL),
        action(
            "downloadurl",
            "ingest-response",
            WFURL=output("ingest-url"),
            WFHTTPMethod="POST",
            WFHTTPBodyType="JSON",
            WFHTTPHeaders=dictionary([
                ("Content-Type", text("application/json")),
                ("X-Ledger-Device-Token", token("token-text")),
            ]),
            WFJSONValues=dictionary([
                ("amount", token("wallet-amount")),
                ("merchant", token("wallet-merchant")),
                ("card", token("wallet-card")),
                ("currency", text("TWD")),
                ("occurred_at", token("request-id")),
                ("request_id", token("request-id")),
            ]),
        ),
        conditional("end-mode", branch, 2),
    ]
    return {
        "WFWorkflowName": "留白自動記帳",
        "WFWorkflowActions": actions,
        "WFWorkflowIcon": {
            "WFWorkflowIconStartColor": 4282601983,
            "WFWorkflowIconGlyphNumber": 59802,
        },
        "WFWorkflowClientVersion": "4033.0.4.3",
        "WFWorkflowClientRelease": "27A000",
        "WFWorkflowOutputContentItemClasses": [],
        "WFWorkflowHasOutputFallback": False,
        "WFWorkflowMinimumClientVersion": 900,
        "WFWorkflowMinimumClientVersionString": "900",
        "WFWorkflowHasShortcutInputVariables": True,
        "WFWorkflowInputContentItemClasses": ["WFStringContentItem", "WFDictionaryContentItem"],
        "WFWorkflowTypes": [],
        "WFQuickActionSurfaces": [],
    }
def validate(data):
    actions = data["WFWorkflowActions"]
    uuids = []
    declared = set()

    def refs(value):
        if isinstance(value, dict):
            if "OutputUUID" in value:
                yield value["OutputUUID"]
            for child in value.values():
                yield from refs(child)
        elif isinstance(value, list):
            for child in value:
                yield from refs(child)

    for item in actions:
        params = item["WFWorkflowActionParameters"]
        assert set(refs(params)) <= declared, "forward or dangling output reference"
        uid = params.get("UUID")
        if uid:
            assert uid not in uuids
            uuids.append(uid)
            declared.add(uid)

    raw = json.dumps(data, ensure_ascii=False)
    for forbidden in ("REPLACE_WITH", "X-Ledger-Token", "TriggerOutput", "getcurrentlocation"):
        assert forbidden not in raw
    assert raw.count("X-Ledger-Device-Token") == 1
    assert raw.count(PAIR_URL) == 1
    assert raw.count(INGEST_URL) == 1
    controls = [
        a["WFWorkflowActionParameters"].get("WFControlFlowMode")
        for a in actions
        if a["WFWorkflowActionIdentifier"] == "is.workflow.actions.conditional"
    ]
    assert controls == [0, 1, 2]
    assert any(a["WFWorkflowActionIdentifier"] == "is.workflow.actions.documentpicker.save" for a in actions)
    assert any(a["WFWorkflowActionIdentifier"] == "is.workflow.actions.documentpicker.open" for a in actions)


if __name__ == "__main__":
    data = build()
    validate(data)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    UNSIGNED.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_bytes(plistlib.dumps(data, fmt=plistlib.FMT_XML, sort_keys=False))
    UNSIGNED.write_bytes(plistlib.dumps(data, fmt=plistlib.FMT_BINARY, sort_keys=False))
    print(f"PASS {OUT.relative_to(ROOT)}: {len(data['WFWorkflowActions'])} actions")
    print(f"PASS {UNSIGNED.relative_to(ROOT)}: binary unsigned shortcut")
    print(f"API base: {API_BASE}")
